package loops;

public class seventeentable {
    public static void main(String[] args) {
        for (int i = 17; i <=170 ; i=i+17) {
            System.out.println(i+"");

        }
        //can also be done as
        for (int i = 1; i <=10 ; i=i+1) {
            System.out.println(i*17+"");

        }
    }
}
